# BARN corridor geometry (verified against grid_files; see gazebo_barn.launch.py)
RES, X_OFF, Y_OFF = 0.15, -4.425, 5.175
START = (-2.25, 1.0, math.pi / 2)      # fixed spawn, matches gazebo_barn.launch.py
STALL_V = 0.03
STALL_NEAR_GOAL = 0.6


def geo(scale):
    """Dataset paths + world geometry for a given spacing scale
    (scaled copies are generated by BARN_dataset/scale_barn.py)."""
    # Always use the scale_barn.py output, including for 1.0: `scaled_1` has
    # the same obstacle poses as the raw dataset but adds the sealed lateral
    # walls (no lidar leakage through cylinder seams) and the planner-padded
    # maps; the raw `world_files`/`map_files` have neither. Earlier rows in
    # barn_results.csv at scale 1.0 (worlds 42/93 smoke runs) used the raw set.
    d = os.path.join(BARN, f"scaled_{scale:g}")
    return {
        "res": RES * scale,
        "x_off": X_OFF * scale,
        "y_off": Y_OFF * scale,
        "start": (START[0] * scale, START[1] * scale, START[2]),
        "worlds": os.path.join(d, "world_files"),
        "maps": os.path.join(d, "map_files"),
        "lists": d,
    }

CSV_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "barn_results.csv")
CSV_FIELDS = ["controller", "world", "rep", "scale", "success", "time_s",
              "opt_len_m", "path_len_m", "min_clear_m", "collided", "stall_s",
              "avg_speed", "result_code"]


def world_goal(idx, g):
    """Goal pose = last point of the BARN optimal path, facing +y."""
    path = np.load(os.path.join(BARN, "path_files", f"path_{idx}.npy"))
    r, c = path[-1]
    return (r * g["res"] + g["x_off"], c * g["res"] + g["y_off"], math.pi / 2)


def optimal_len(idx, g):
    """Straight run-up from START to the field entry + BARN path length (m)."""
    path = np.load(os.path.join(BARN, "path_files", f"path_{idx}.npy")).astype(float)
    xy = np.column_stack([path[:, 0] * g["res"] + g["x_off"],
                          path[:, 1] * g["res"] + g["y_off"]])
    seg = float(np.sum(np.hypot(*(np.diff(xy, axis=0).T))))
    entry = float(math.hypot(xy[0, 0] - g["start"][0], xy[0, 1] - g["start"][1]))
    return entry + seg


def load_world_list(tag, g):
    """'safe' / 'tight' from susag_suitable_worlds.txt, or a file of IDs."""
    if tag in ("safe", "tight"):
        want = "SAFE" if tag == "safe" else "TIGHT"
        txt = open(os.path.join(g["lists"], "susag_suitable_worlds.txt")).read()
        block = txt.split(want, 1)[1]
        ids = block[block.index("["):block.index("]") + 1]
        return list(eval(ids))
    return [int(line) for line in open(tag) if line.strip()]


