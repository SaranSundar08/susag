class BarnBench(Node):
    def __init__(self):
        super().__init__(
            "barn_bench",
            parameter_overrides=[Parameter("use_sim_time", value=True)])
        best_effort = QoSProfile(depth=10,
                                 reliability=ReliabilityPolicy.BEST_EFFORT,
                                 history=HistoryPolicy.KEEP_LAST)
        self.create_subscription(Odometry, "/odom", self._odom_cb, best_effort)
        # Collision proxy reads BOTH lidars (min range over either); the
        # costmaps consume them as separate sources and AMCL uses the front.
        self.create_subscription(LaserScan, "/front_scan", self._scan_cb, best_effort)
        self.create_subscription(LaserScan, "/rear_scan", self._scan_cb, best_effort)
        self.create_subscription(PoseWithCovarianceStamped, "/amcl_pose",
                                 self._amcl_cb, 10)
        self.initpose_pub = self.create_publisher(PoseWithCovarianceStamped,
                                                  "/initialpose", 10)
        self.nav = ActionClient(self, NavigateToPose, "navigate_to_pose")
        self.set_params = self.create_client(
            SetParameters, "/controller_server/set_parameters")
        self.reset_state()

    def reset_state(self):
        self.pose = None
        self.vlin = 0.0
        self.amcl_seen = False
        self.min_clear = float("inf")
        self.path_len = 0.0
        self.stall_s = 0.0
        self._last_xy = None
        self._last_t = None
        self.collision_thresh = 0.0

    def _odom_cb(self, msg):
        p = msg.pose.pose.position
        self.pose = (p.x, p.y)
        v = msg.twist.twist.linear
        self.vlin = math.hypot(v.x, v.y)

    def _scan_cb(self, msg):
        for r in msg.ranges:
            if msg.range_min < r < self.min_clear:
                self.min_clear = r

    def _amcl_cb(self, msg):
        self.amcl_seen = True

    def sim_now(self):
        return self.get_clock().now().nanoseconds * 1e-9

    # -- bring-up helpers ---------------------------------------------------
    def wait_for(self, cond, timeout, what):
        t0 = time.time()
        while rclpy.ok() and time.time() - t0 < timeout:
            rclpy.spin_once(self, timeout_sec=0.2)
            if cond():
                return True
        self.get_logger().error(f"timed out waiting for {what}")
        return False

    def publish_initial_pose(self, start=START):
        msg = PoseWithCovarianceStamped()
        msg.header.frame_id = "map"
        msg.pose.pose.position.x = start[0]
        msg.pose.pose.position.y = start[1]
        msg.pose.pose.orientation.z = math.sin(start[2] / 2.0)
        msg.pose.pose.orientation.w = math.cos(start[2] / 2.0)
        msg.pose.covariance[0] = msg.pose.covariance[7] = 0.05
        msg.pose.covariance[35] = 0.03
        for _ in range(5):
            msg.header.stamp = self.get_clock().now().to_msg()
            self.initpose_pub.publish(msg)
            rclpy.spin_once(self, timeout_sec=0.4)
        return self.wait_for(lambda: self.amcl_seen, 15.0, "AMCL pose")

    def wait_node_active(self, node_name, timeout=60.0):
        """Block until a lifecycle node reports state 'active'.

        The nav2 action servers are discoverable while their node is still
        inactive, so server_is_ready() alone sends goals into the void."""
        cli = self.create_client(GetState, f"/{node_name}/get_state")
        t0 = time.time()
        try:
            while rclpy.ok() and time.time() - t0 < timeout:
                if cli.wait_for_service(timeout_sec=1.0):
                    fut = cli.call_async(GetState.Request())
                    rclpy.spin_until_future_complete(self, fut, timeout_sec=2.0)
                    res = fut.result()
                    if res is not None and res.current_state.label == "active":
                        return True
                rclpy.spin_once(self, timeout_sec=0.2)
        finally:
            self.destroy_client(cli)
        self.get_logger().error(f"{node_name} never became active")
        return False

    def set_variant(self, variant):
        if not self.set_params.wait_for_service(timeout_sec=10.0):
            return False
        req = SetParameters.Request()
        pv = ParameterValue(type=ParameterType.PARAMETER_STRING,
                            string_value=variant)
        req.parameters = [ParamMsg(name="FollowPath.mppi_variant", value=pv)]
        fut = self.set_params.call_async(req)
        rclpy.spin_until_future_complete(self, fut, timeout_sec=10.0)
        res = fut.result()
        ok = res is not None and all(r.successful for r in res.results)
        if ok:
            self.get_logger().info(f"mppi_variant := {variant}")
        return ok

    # -- the trial ----------------------------------------------------------
    def run_trial(self, goal_xyyaw, timeout_s, collision_thresh):
        gx, gy, gyaw = goal_xyyaw
        self.min_clear = float("inf")
        self.path_len = 0.0
        self.stall_s = 0.0
        self._last_xy = None
        self._last_t = None
        self.collision_thresh = collision_thresh

        goal = NavigateToPose.Goal()
        ps = PoseStamped()
        ps.header.frame_id = "map"
        ps.header.stamp = self.get_clock().now().to_msg()
        ps.pose.position.x = float(gx)
        ps.pose.position.y = float(gy)
        ps.pose.orientation.z = math.sin(gyaw / 2.0)
        ps.pose.orientation.w = math.cos(gyaw / 2.0)
        goal.pose = ps

        # Retry rejected sends: right after activation bt_navigator can still
        # refuse the first goal or two while its costmaps warm up.
        handle = None
        t0_retry = time.time()
        while rclpy.ok() and time.time() - t0_retry < 30.0:
            ps.header.stamp = self.get_clock().now().to_msg()
            send_fut = self.nav.send_goal_async(goal)
            rclpy.spin_until_future_complete(self, send_fut, timeout_sec=10.0)
            handle = send_fut.result()
            if handle is not None and handle.accepted:
                break
            self.get_logger().warn("goal not accepted yet, retrying...")
            handle = None
            time.sleep(2.0)
        if handle is None:
            return dict(success=0, time_s=0.0, result_code=-1)

        result_fut = handle.get_result_async()
        t0_wall, t0_sim = time.time(), self.sim_now()
        while rclpy.ok():
            rclpy.spin_once(self, timeout_sec=0.1)
            self._accumulate((gx, gy))
            if result_fut.done():
                status = result_fut.result().status
                return dict(success=int(status == 4),
                            time_s=self.sim_now() - t0_sim,
                            result_code=status)
            if time.time() - t0_wall > timeout_s:
                handle.cancel_goal_async()
                rclpy.spin_once(self, timeout_sec=0.5)
                return dict(success=0, time_s=self.sim_now() - t0_sim,
                            result_code=0)
        return dict(success=0, time_s=0.0, result_code=-1)

    def _accumulate(self, goal_xy):
        if self.pose is None:
            return
        now = time.time()
        x, y = self.pose
        if self._last_xy is not None:
            self.path_len += math.hypot(x - self._last_xy[0], y - self._last_xy[1])
            d_goal = math.hypot(goal_xy[0] - x, goal_xy[1] - y)
            if self.vlin < STALL_V and d_goal > STALL_NEAR_GOAL:
                self.stall_s += now - self._last_t
        self._last_xy = (x, y)
        self._last_t = now


