# BARN benchmark orchestrator for the SLIP controller study
# (ROS 2 Humble, Gazebo Classic, nav2).
#
# Unlike benchmark_tgmppi.py (which assumes sim+nav2 are already up), this
# script owns the whole lifecycle per trial:
#   1. launch headless gzserver with BARN world i  (gazebo_barn.launch.py gui:=false)
#   2. launch nav2 with the matching BARN map and the controller's params file
#   3. publish the AMCL initial pose (= the fixed BARN spawn pose)
#   4. for fork variants, set FollowPath.mppi_variant at runtime
#   5. send the goal (field exit, from path_files/path_i.npy), record metrics
#   6. tear everything down and move to the next (controller, world, rep)
#
# Controllers:
#   vanilla | log | lowpass | biased   -> navigation_sim.yaml + runtime mppi_variant
#   tgmppi                             -> navigation_tgmppi.yaml (own plugin)
#
# Metrics per trial (CSV row):
#   success        1 if NavigateToPose SUCCEEDED within timeout
#   time_s         SIM-time seconds from goal accept to result
#   opt_len_m      optimal path length from BARN path_files (start->exit)
#   path_len_m     integrated /odom travel
#   min_clear_m    min /front_scan or /rear_scan range over the run (collision proxy)
#   collided       1 if min_clear_m < --collision-thresh at any point
#   stall_s        cumulative time |v| < STALL_V while far from goal
#   avg_speed      path_len_m / time_s
#   result_code    4=SUCCEEDED, 6=ABORTED, 0=timeout, -1=rejected/error
# The BARN score  success * OT / clip(AT, OT, 8*OT)  (OT = opt_len / max_speed)
# is computed in --report so max_speed can be changed without rerunning.
#
# Usage:
#   python3 benchmark_barn.py --controllers vanilla log tgmppi \
#       --worlds 0 5 9 42 93 --reps 3
#   python3 benchmark_barn.py --worlds-file safe          # 114 SAFE-tier worlds
#   python3 benchmark_barn.py --report [--max-speed 1.0]

