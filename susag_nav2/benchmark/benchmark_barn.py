class Launch:
    """A ros2 launch subprocess we can SIGINT cleanly as a group."""

    def __init__(self, args, log_path):
        self.log = open(log_path, "w")
        self.proc = subprocess.Popen(
            args, stdout=self.log, stderr=subprocess.STDOUT,
            preexec_fn=os.setsid)

    def stop(self, timeout=15.0):
        if self.proc.poll() is None:
            try:
                os.killpg(os.getpgid(self.proc.pid), signal.SIGINT)
                self.proc.wait(timeout=timeout)
            except (subprocess.TimeoutExpired, ProcessLookupError):
                try:
                    os.killpg(os.getpgid(self.proc.pid), signal.SIGKILL)
                except ProcessLookupError:
                    pass
        self.log.close()


def kill_strays():
    """Belt-and-braces: nothing from a previous trial may survive."""
    for pat in ("gzserver", "gzclient", "component_container_isolated",
                "robot_state_publisher", "joint_state_publisher"):
        subprocess.run(["pkill", "-f", pat], capture_output=True)
    time.sleep(2.0)


