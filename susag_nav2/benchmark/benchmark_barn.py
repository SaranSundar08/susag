def append_csv(row):
    new = not os.path.exists(CSV_PATH)
    with open(CSV_PATH, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=CSV_FIELDS)
        if new:
            w.writeheader()
        w.writerow(row)


def run_single_trial(ctrl, world, rep, timeout, collision_thresh, scale=1.0):
    """One complete trial in THIS process. Called in a fresh child process per
    trial: a long-lived DDS participant that watches nav2 restart a dozen
    times stops discovering the new lifecycle services (stale FastDDS graph),
    so every trial gets a brand-new rclpy context."""
    log_dir = os.path.join(os.path.dirname(CSV_PATH), "logs")
    os.makedirs(log_dir, exist_ok=True)
    g = geo(scale)
    goal = world_goal(world, g)
    opt = optimal_len(world, g)
    params_file, variant = CONTROLLERS[ctrl]
    tag = f"{ctrl}_w{world}_r{rep}"

    kill_strays()
    rclpy.init()
    bench = BarnBench()
    gz = nav = None
    try:
        gz = Launch(
            ["ros2", "launch", "susag_updated_model_description",
             "gazebo_barn.launch.py", f"world_idx:={world}",
             f"worlds_dir:={g['worlds']}",
             f"x_pose:={g['start'][0]}", f"y_pose:={g['start'][1]}",
             "gui:=false"],
            os.path.join(log_dir, f"gz_{tag}.log"))
        if not bench.wait_for(lambda: bench.pose is not None,
                              60.0, "gazebo /odom"):
            return 1

        nav = Launch(
            ["ros2", "launch", "susag_nav2", "navigation.launch.py",
             "sim:=true", "rviz:=false",
             f"map:={g['maps']}/yaml_{world}.yaml",
             f"nav2_params:={params_file}"],
            os.path.join(log_dir, f"nav2_{tag}.log"))
        # Order matters: AMCL needs the initial pose before it publishes
        # map->odom, and the costmaps (and therefore bt_navigator's
        # activation) block on that transform.
        ok = bench.wait_node_active("amcl")
        ok = ok and bench.publish_initial_pose(g["start"])
        ok = ok and bench.wait_node_active("bt_navigator")
        ok = ok and bench.wait_node_active("controller_server")
        ok = ok and bench.wait_for(
            lambda: bench.nav.server_is_ready(), 30.0, "nav2 action server")
        if ok and variant is not None:
            ok = bench.set_variant(variant)
        time.sleep(2.0)  # let costmaps fill in

        if ok:
            m = bench.run_trial(goal, timeout, collision_thresh)
        else:
            m = dict(success=0, time_s=0.0, result_code=-1)

        clear = bench.min_clear if bench.min_clear != float("inf") else -1
        row = {
            "controller": ctrl, "world": world, "rep": rep, "scale": scale,
            "success": m["success"], "time_s": round(m["time_s"], 2),
            "opt_len_m": round(opt, 2),
            "path_len_m": round(bench.path_len, 2),
            "min_clear_m": round(clear, 3),
            "collided": int(0 <= clear < collision_thresh),
            "stall_s": round(bench.stall_s, 2),
            "avg_speed": round(bench.path_len / m["time_s"], 3)
                         if m["time_s"] > 1e-3 else 0.0,
            "result_code": m["result_code"],
        }
        append_csv(row)
        print(f"  -> success={row['success']} t={row['time_s']}s "
              f"path={row['path_len_m']}m clear={row['min_clear_m']}m "
              f"collided={row['collided']}", flush=True)
        return 0
    finally:
        if nav is not None:
            nav.stop()
        if gz is not None:
            gz.stop()
        bench.destroy_node()
        rclpy.shutdown()


def run_matrix(args):
    """Loop the matrix, one fresh child process per trial (see run_single_trial)."""
    for world in args.worlds:
        for ctrl in args.controllers:
            for rep in range(args.reps):
                print(f"=== world {world} | {ctrl} | rep {rep} ===", flush=True)
                subprocess.run(
                    [sys.executable, os.path.abspath(__file__),
                     "--_trial", ctrl, str(world), str(rep),
                     "--scale", str(args.scale),
                     "--timeout", str(args.timeout),
                     "--collision-thresh", str(args.collision_thresh)])
    kill_strays()
    print(f"done -> {CSV_PATH}")


def print_report(max_speed):
    if not os.path.exists(CSV_PATH):
        print(f"no results at {CSV_PATH}")
        return
    import statistics as st
    rows = list(csv.DictReader(open(CSV_PATH)))
    groups = {}
    for r in rows:
        groups.setdefault(r["controller"], []).append(r)

    def score(r):
        if r["success"] != "1":
            return 0.0
        ot = float(r["opt_len_m"]) / max_speed
        at = float(r["time_s"])
        return ot / min(max(at, ot), 8.0 * ot)

    hdr = (f"{'controller':<10}{'n':>5}{'succ%':>7}{'coll%':>7}{'t_s':>8}"
           f"{'path_m':>8}{'clear_m':>9}{'stall_s':>9}{'score':>8}")
    print(f"BARN report (max_speed={max_speed} m/s; score = succ*OT/clip(AT,OT,8OT))")
    print(hdr)
    print("-" * len(hdr))
    for ctrl in sorted(groups):
        rs = groups[ctrl]
        n = len(rs)
        succ = [r for r in rs if r["success"] == "1"]
        t = [float(r["time_s"]) for r in succ]
        pl = [float(r["path_len_m"]) for r in succ]
        clr = [float(r["min_clear_m"]) for r in rs if float(r["min_clear_m"]) >= 0]
        stall = [float(r["stall_s"]) for r in rs]
        coll = [r for r in rs if r["collided"] == "1"]
        sc = [score(r) for r in rs]
        print(f"{ctrl:<10}{n:>5}{100*len(succ)/n:>6.0f}%{100*len(coll)/n:>6.0f}%"
              f"{st.mean(t) if t else float('nan'):>8.1f}"
              f"{st.mean(pl) if pl else float('nan'):>8.1f}"
              f"{st.mean(clr) if clr else float('nan'):>9.2f}"
              f"{st.mean(stall) if stall else float('nan'):>9.1f}"
              f"{st.mean(sc):>8.3f}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--controllers", nargs="+", default=["vanilla", "tgmppi"],
                    choices=list(CONTROLLERS.keys()))
    ap.add_argument("--worlds", nargs="+", type=int,
                    help="explicit BARN world ids")
    ap.add_argument("--worlds-file",
                    help="'safe', 'tight', or a file with one id per line")
    ap.add_argument("--reps", type=int, default=1)
    ap.add_argument("--scale", type=float, default=1.0,
                    help="BARN spacing scale; needs scaled_<s>/ generated by "
                         "BARN_dataset/scale_barn.py (e.g. 1.2, 1.4)")
    ap.add_argument("--timeout", type=float, default=120.0,
                    help="per-trial wall-time ceiling (s)")
    ap.add_argument("--collision-thresh", type=float, default=0.12,
                    help="min /scan range treated as a collision (proxy)")
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--max-speed", type=float, default=1.0,
                    help="vx_max used for the BARN score in --report")
    ap.add_argument("--_trial", nargs=3, metavar=("CTRL", "WORLD", "REP"),
                    help=argparse.SUPPRESS)  # internal: run one trial in-process
    args = ap.parse_args()

    if args._trial:
        ctrl, world, rep = args._trial
        sys.exit(run_single_trial(ctrl, int(world), int(rep),
                                  args.timeout, args.collision_thresh,
                                  args.scale))
    if args.report:
        print_report(args.max_speed)
        return
    if args.worlds_file:
        args.worlds = load_world_list(args.worlds_file, geo(args.scale))
    if not args.worlds:
        ap.error("--worlds or --worlds-file required")
    run_matrix(args)


if __name__ == "__main__":
    main()
